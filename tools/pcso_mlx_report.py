def main():
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument('--check', action='store_true')
    args = ap.parse_args()
    out, text = build()
    doc = narrative(out, hashlib.sha256(text.encode()).hexdigest())
    superseded = ('# Superseded MLX report\n\nThe previous narrative and aggregate are superseded by '
        '`docs/RESULTS_PCSO_MLX_BACKEND_2026-09-23.md` and the regenerated '
        '`pcso_mlx_null_calibration_2026-09-23.json`.\n\nOnly source JSONs listed in the new aggregate hash manifest '
        'are current evidence. Other legacy logs/probes and `.pi/mlx_finish/` outputs are historical and must not be used as final evidence.\n')
    for path, content in [(AGGREGATE,text),(DOC,doc),(FOLDER / 'pcso_mlx_report_2026-09-23.md',superseded)]:
        if args.check:
            assert path.read_bytes() == content.encode(), f'{path}: regeneration differs'
        else:
            path.write_text(content)
    print('byte-identical aggregation and narrative' if args.check else f'wrote {AGGREGATE} and {DOC}')


if __name__ == '__main__':
    main()
