def digest(path):
    return hashlib.sha256(path.read_bytes()).hexdigest()


def screen_sensitivity(n=400, m=10000, p0=.005, alpha=.05, power=.8):
    critical = math.sqrt(-.5 * math.log(alpha / 2)) * math.sqrt(1/n + 1/m)
    # DKW + union bound: each empirical CDF stays within epsilon_i with
    # probability >= 1-(1-power)/2; their errors add under any alternative.
    sufficient = critical + sum(math.sqrt(math.log(4 / (1-power)) / (2*k)) for k in (n, m))
    zcrit, zpower = norm.ppf(1-alpha/2), norm.ppf(power)
    def equation(delta):
        p1 = p0 + delta
        pooled = (n*p0 + m*p1)/(n+m)
        return delta - zcrit*math.sqrt(pooled*(1-pooled)*(1/n+1/m)) - zpower*math.sqrt(p0*(1-p0)/n+p1*(1-p1)/m)
    fisher_delta = brentq(equation, 1e-12, .5)
    return {'alpha': alpha, 'target_power': power, 'cpu_n': n, 'mlx_n': m,
            'ks_rejection_D_approx': critical,
            'ks_80pct_power_sufficient_CDF_separation': sufficient,
            'ks_MDE_method': 'conservative sufficient separation via DKW union bound; not an exact minimum',
            'fisher_80pct_MDE_rate_difference_approx': fisher_delta,
            'fisher_reference_cpu_rate': p0,
            'fisher_implied_mlx_rate_approx': p0+fisher_delta,
            'fisher_MDE_method': 'two-proportion normal approximation; discrete Fisher power can differ, especially with 2 expected CPU events',
            'interpretation': 'gross screens cannot resolve arithmetic residuals; paired bounds are primary'}


def build():
    sources = {}
    def read(name):
        path = FOLDER / name
        sources[str(path.relative_to(ROOT))] = digest(path)
        return json.loads(path.read_text())
    matched, paired = {}, {}
    for name, m in [(n, 32) for n in sim.PORTED] + [('cp_nest', 128)]:
        key = f'{name}_m{m}'
        matched[key] = read(f'pcso_mlx_matched_{key}.json')
        paired[key] = read(f'pcso_mlx_paired_{key}.json')
        for artifact in (matched[key], paired[key]):
            assert artifact['_meta']['schedule_draws'] == 994
            for value in artifact['devices'].values():
                assert_paired(value['paired'])
                if artifact['drift_asserted']:
                    assert value['drift']['extrapolated_994_bound'] < 1e-4
    v0_distributions = {}
    for key, artifact in paired.items():
        if 'v0_final' in artifact['cpu']:
            v0_distributions[key] = {}
            for backend, values in [('cpu', artifact['cpu']), ('gpu', artifact['devices']['gpu']['values'])]:
                v = np.asarray(values['v0_final'])
                v0_distributions[key][backend] = {'mean': float(v.mean()), 'q50': float(np.quantile(v,.5)), 'q90': float(np.quantile(v,.9)), 'q99': float(np.quantile(v,.99)), 'fraction_ge_0_9': float((v >= .9).mean())}
    power, power_large = {}, {}
    for name in ('cp_nest', 'tilt_linear'):
        power[name] = read(f'pcso_mlx_power_{name}_m128.json')
        power_large[name] = read(f'pcso_mlx_power_{name}_mlx_2000.json')
        for artifact in (power[name], power_large[name]):
            assert artifact['theta1'] == .05 and artifact['_meta']['M'] == 128
            assert artifact['_meta']['schedule_draws'] == 994
        assert power[name]['n_streams'] == 200
        assert power_large[name]['models'][name]['n_streams'] == 2000
        for value in power[name]['devices'].values():
            assert_paired(value['paired'])
    screens, timings, summaries = {}, {}, {}
    benchmarks = []
    for name in sim.MODELS:
        jobs = {(b, n): read(f'pcso_mlx_bench_{name}_{b}_{n}.json')
                for b, n in [('cpu',400), ('mlx',400), ('mlx',10000)]}
        benchmarks.extend(jobs.values())
        cpu, gpu = jobs['cpu',400], jobs['mlx',10000]
        result = {k: np.asarray(gpu[k]) for k in ('sup', 'log_sr_max')}
        screens[name] = sim.compare_null(cpu['sup'], cpu['log_sr_max'], result)
        if name == 'uniform':
            screens[name]['analytic_reference'] = True
            screens[name]['max_abs_sr_roundoff'] = float(np.max(np.abs(np.asarray(cpu['log_sr_max'])[:,None]-result['log_sr_max'])))
            screens[name]['point_mass_note'] = ('Unrounded KS distinguishes disjoint point masses separated by host roundoff (~1e-15 nats); '
                'the old 5e-324 p-value measured that tie, not a model discrepancy. Raw point-mass KS removed; rounded SR is included in verdict.')
        timings[name] = {f'{b}{n}': job['wall_s'] for (b,n),job in jobs.items()}
        summaries[name] = gpu['summary']
    source_files = ['src/pcso_mlx_sim.py', 'src/pcso_mlx_benchmark.py', 'src/pcso_model_registry.py',
                    'tests/test_pcso_mlx_sim.py', 'tools/pcso_mlx_validate.py', 'tools/pcso_mlx_bench_all.py',
                    'tools/pcso_mlx_remote.py', 'tools/pcso_mlx_report.py', 'tools/snapshot_commitment.py']
    scripts = {p: digest(ROOT / p) for p in source_files}
    validation = [*matched.values(), *paired.values(), *power.values()]
    for artifact in [*validation, *power_large.values(), *benchmarks]:
        assert artifact['_meta']['schedule_draws'] == 994
        assert artifact['_meta']['schedule_sha256'] == '7ca585656595199a76a78c4834eed7aa1a0defa536df73c3f78351bd159db9cb'
        for path, sha in artifact['_meta']['source_sha256'].items():
            assert scripts[path] == sha, (path, 'stale source artifact')
    for artifact in validation:
        assert artifact['script_sha256'] == scripts['tools/pcso_mlx_validate.py'], 'stale validation script'
    for artifact in benchmarks:
        assert artifact['script_sha256'] == scripts['src/pcso_mlx_benchmark.py'], 'stale benchmark script'
    equivalence = read('pcso_mlx_equivalence_2026-09-23.json')
    cpu_without_mlx = read('pcso_mlx_cpu_without_mlx.json')
    assert cpu_without_mlx['_meta']['device'] == 'unavailable'
    assert cpu_without_mlx['_meta']['mlx_version'] is None
    assert cpu_without_mlx['script_sha256'] == scripts['src/pcso_mlx_benchmark.py']
    for path, sha in cpu_without_mlx['_meta']['source_sha256'].items():
        assert scripts[path] == sha
    registry_diff = subprocess.check_output(['git','diff','origin/master','--','src/pcso_model_registry.py'], cwd=ROOT, text=True)
    assert not registry_diff
    out = {'status': 'exploratory, not registered', 'base_sha': subprocess.check_output(['git','rev-parse','HEAD'],cwd=ROOT,text=True).strip(),
           'registry_diff_origin_master': registry_diff, 'schedule_cutoff': '2026-09-20',
           'schedule_note': 'New base has 999 draws; the requested 994-draw schedule is its exact prefix.',
           'ported': list(sim.PORTED), 'uniform': 'analytic reference (no GPU computation)', 'bounds': BOUNDS,
           'matched': matched, 'paired': paired, 'v0_distributions': v0_distributions,
           'power': power, 'power_mlx_2000': power_large, 'test_equivalence': equivalence,
           'cpu_without_mlx': cpu_without_mlx, 'gross_screens': screens,
           'screen_sensitivity': screen_sensitivity(), 'timing_s': timings, 'null_10000': summaries,
           'source_json_sha256': sources, 'script_sha256': scripts,
           'grid': 'not run; lead will pre-declare separately',
           'sampling_note': 'The 400-stream and 10000-stream benchmark artifacts are disjoint samples (different generator seeds); neither is a prefix of the other.',
           'issues': ['Float32 residual is device-dependent; equivalence bounds are empirical on the specified inputs, not a proof for all inputs.',
                      'Independent review CLI was unavailable in the prior round: pi --help reported EPERM creating its settings lock. It was not retried; this continuation received self-review only. No alternate permissions or credentials attempted.'],
           'ledger_note': 'snapshot_commitment.py hashes docs/RESULTS_*; the picker narrative appears in its snapshot-format blocks at ledger lines 1287/1349. results/ is excluded. Use the existing snapshot tool, never a hand-edited row.'}
    out['test_log_sha256'] = {}
    for host in ('local','m5'):
        path = FOLDER / f'pcso_mlx_tests_{host}_2026-09-23.log'
        out['tests_'+host] = path.read_text().strip().splitlines()[-1]
        out['test_log_sha256'][str(path.relative_to(ROOT))] = digest(path)
    text = json.dumps(out, indent=2, allow_nan=False) + '\n'
    return out, text


